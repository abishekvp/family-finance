const { AndroidConfig, withAndroidManifest, withDangerousMod } = require("@expo/config-plugins");
const fs = require("fs");
const path = require("path");

/**
 * Release APKs get no cleartext-HTTP allowance — `usesCleartextTraffic` lives only in the
 * debug manifest — so a release build pointed at an `http://` dev server on the LAN dies with
 * "CLEARTEXT communication not permitted by network security policy". Rather than switching
 * cleartext on globally, this emits a network-security config that permits it for localhost
 * plus whatever hosts `EXPO_PUBLIC_DEV_CLEARTEXT_HOSTS` lists (comma-separated), leaving
 * HTTPS-only enforcement in place for everything else.
 *
 * `android/` is generated and gitignored, so this has to be a plugin: editing the generated
 * manifest directly would be wiped by the next `expo prebuild`.
 */

function cleartextHosts() {
  const extra = (process.env.EXPO_PUBLIC_DEV_CLEARTEXT_HOSTS || "")
    .split(",")
    .map((h) => h.trim())
    .filter(Boolean);
  // Derive the host from the API URL too, so a single env var is usually enough.
  const apiUrl = process.env.EXPO_PUBLIC_API_URL;
  if (apiUrl) {
    try {
      const { protocol, hostname } = new URL(apiUrl);
      if (protocol === "http:") extra.push(hostname);
    } catch {
      // Not a parseable URL — nothing to derive.
    }
  }
  return [...new Set(["localhost", "127.0.0.1", "10.0.2.2", ...extra])];
}

function configXml(hosts) {
  const entries = hosts.map((h) => `        <domain includeSubdomains="false">${h}</domain>`).join("\n");
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withLanCleartext.js — do not edit by hand. -->
<network-security-config>
    <domain-config cleartextTrafficPermitted="true">
${entries}
    </domain-config>
</network-security-config>
`;
}

module.exports = function withLanCleartext(config) {
  const hosts = cleartextHosts();

  config = withDangerousMod(config, [
    "android",
    (cfg) => {
      const xmlDir = path.join(cfg.modRequest.platformProjectRoot, "app", "src", "main", "res", "xml");
      fs.mkdirSync(xmlDir, { recursive: true });
      fs.writeFileSync(path.join(xmlDir, "network_security_config.xml"), configXml(hosts));
      return cfg;
    },
  ]);

  return withAndroidManifest(config, (cfg) => {
    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(cfg.modResults);
    app.$["android:networkSecurityConfig"] = "@xml/network_security_config";
    return cfg;
  });
};
